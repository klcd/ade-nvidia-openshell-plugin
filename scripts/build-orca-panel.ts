#!/usr/bin/env bun
import fs from 'node:fs'
import path from 'node:path'

const repoRoot = path.resolve(import.meta.dir, '..')
const panelSrcDir = path.join(repoRoot, 'orca-plugin', 'src', 'panel')
const outHtmlPath = path.join(repoRoot, 'orca-plugin', 'panel', 'index.html')

const css = fs.readFileSync(path.join(panelSrcDir, 'styles.css'), 'utf8').trim()
const bodyHtml = fs.readFileSync(path.join(panelSrcDir, 'template.html'), 'utf8').trim()

const buildResult = await Bun.build({
  entrypoints: [path.join(panelSrcDir, 'main.ts')],
  target: 'browser',
  format: 'iife',
  minify: false,
})

if (!buildResult.success || buildResult.outputs.length === 0) {
  console.error('Failed to bundle OpenShell Policies panel:', buildResult.logs)
  process.exit(1)
}

const js = (await buildResult.outputs[0].text()).trim()

const html = `<!doctype html>
<!-- Generated by scripts/build-orca-panel.ts from orca-plugin/src/panel/* — do not edit directly -->
<html lang="en">
<head>
<meta charset="utf-8">
<title>OpenShell Policies &amp; CLI Commands</title>
<style>
${css}
</style>
</head>
<body>
${bodyHtml}
<script>
${js}
</script>
</body>
</html>
`

fs.mkdirSync(path.dirname(outHtmlPath), { recursive: true })
fs.writeFileSync(outHtmlPath, html, 'utf8')
console.log(`Built ${path.relative(repoRoot, outHtmlPath)} (${(Buffer.byteLength(html) / 1024).toFixed(1)} KB)`)
